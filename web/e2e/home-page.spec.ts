import { expect, test } from "@playwright/test";

test("entry home links to real workspaces and keeps old deep links", async ({ page }, testInfo) => {
  const setup = await page.request.post("/test/calibration", { data: {} });
  expect(setup.ok()).toBeTruthy();
  const fixture = await setup.json();
  const writes: string[] = [];
  page.on("request", req => { if (req.method() !== "GET" && req.url().includes("/api/")) writes.push(req.url()); });
  await page.goto("/");
  await expect(page.getByRole("heading", { level: 1, name: /每个好作品\s*都不止于一次/ })).toBeVisible();
  await expect(page.locator(".home-hero > p")).toHaveText("把这一次的创作经验，变成下一次的起点。");
  await expect(page.locator(".home-hero h1")).toHaveCSS("color", "rgb(29, 29, 31)");
  await expect(page.getByRole("link", { name: "进入工作台", exact: true })).toHaveCount(1);
  await expect(page.locator(".home-page svg")).toHaveCount(1);
  await expect(page.locator(".home-icon-mark img")).toHaveCount(4);
  await expect.poll(() => page.locator(".home-icon-mark img").evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth >= 256))).toBe(true);
  await expect(page.locator(".home-icon-mark").first()).toHaveCSS("border-top-width", "0px");
  await expect(page.locator("#home-title")).not.toContainText(/[，。]/);
  await expect(page.locator(".home-page footer")).toHaveCount(0);
  await expect(page.getByRole("navigation", { name: "主导航" })).toHaveCount(0);
  const account = page.locator(".home-account").filter({ hasText: "[隔离验证] 校准账号" });
  await expect(account).toBeVisible();
  await expect(account).toHaveAttribute("href", `/?creator=${fixture.creator_id}`);
  const primary = page.locator(".home-actions").getByRole("link", { name: "进入工作台" });
  const secondary = page.getByRole("navigation", { name: "首页导航" }).getByRole("link", { name: "Skill 库", exact: true });
  await expect(primary).toHaveCSS("background-color", "rgb(29, 29, 31)");
  await primary.hover();
  await expect(primary).toHaveCSS("background-color", "rgb(54, 54, 56)");
  await secondary.hover();
  await expect(secondary).toHaveCSS("text-decoration-line", "none");
  await primary.focus();
  await expect(primary).toBeFocused();
  await page.locator("#home-title").click();
  await expect(page.locator("#home-title > span").last()).toHaveCSS("filter", "blur(0px)");
  await page.screenshot({ path: testInfo.outputPath("home-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 2550, height: 1292 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(2550);
  await page.screenshot({ path: testInfo.outputPath("home-wide.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 900 });
  expect(writes).toEqual([]);
  await primary.press("Enter");
  await expect(page).toHaveURL(/\/workspace$/);
  await expect(page.getByRole("navigation", { name: "主导航" })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("navigation", { name: "主导航" })).toBeVisible();
  await page.getByRole("link", { name: "CreatorOS 首页", exact: true }).click();
  await expect(page.getByRole("heading", { level: 1, name: /每个好作品/ })).toBeVisible();
  await account.click();
  expect(new URL(page.url()).searchParams.get("creator")).toBe(fixture.creator_id);
  await expect(page.getByRole("navigation", { name: "账号工作区" })).toBeVisible();
  await page.goto(`/?series=${fixture.series_id}`);
  await expect(page.getByRole("heading", { level: 1, name: "[隔离验证] 故事校准" })).toBeVisible();
  await page.goto(`/runs/${fixture.run_id}`);
  await expect(page.getByRole("region", { name: "验收与返工" })).toBeVisible();
  await page.goto("/");
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(primary).toBeVisible();
  await expect(page.locator("#home-title > span").last()).toHaveCSS("filter", "blur(0px)");
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: testInfo.outputPath("home-mobile.png"), fullPage: true });
  await secondary.click();
  await expect(page).toHaveURL(/\/skills$/);
  await expect(page.getByRole("navigation", { name: "主导航" })).toBeVisible();
  const evidence = await (await page.request.get("/test/calibration-evidence")).json();
  expect(evidence.protected_records).toEqual(fixture.baseline_records);
});

test("home motion is bounded and respects keyboard, touch and reduced motion", async ({ page, browser }, testInfo) => {
  await page.goto("/");
  const line = page.locator("#home-title > span").first();
  await expect(line).toHaveCSS("animation-name", "home-title-reveal");
  await expect(line).toHaveCSS("filter", "blur(0px)");
  const icon = page.locator(".home-icon-work");
  const arm = page.locator(".clapper-arm");
  const puzzle = page.getByRole("button", { name: "拼接积木" });
  await expect(page.locator(".clapper-scene")).toHaveCSS("filter", "grayscale(1) contrast(1.8) brightness(0.85)");
  await icon.hover();
  await expect.poll(() => arm.evaluate(el => el.getAnimations().filter(a => a.playState === "running").length)).toBe(1);
  await arm.evaluate(el => { const animation = el.getAnimations()[0]; animation.pause(); animation.currentTime = 270; });
  await expect.poll(() => arm.evaluate(el => {
    const matrix = new DOMMatrix(getComputedStyle(el).transform);
    return Math.round(Math.atan2(matrix.b, matrix.a) * 180 / Math.PI);
  })).toBe(18);
  await page.screenshot({ path: testInfo.outputPath("home-clap-closed.png"), fullPage: true });
  await arm.evaluate(el => el.getAnimations()[0].finish());
  await expect(arm).toHaveCSS("transform", "none");
  await puzzle.hover();
  await expect(puzzle).toHaveAttribute("data-joined", "true");
  await expect(page.locator(".puzzle-arrival")).toHaveCSS("opacity", "1");
  await expect(page.locator(".puzzle-base")).toHaveCSS("transform", /matrix\(0\.65/);
  await page.screenshot({ path: testInfo.outputPath("home-puzzle-joined.png"), fullPage: true });
  await page.mouse.move(0, 0);
  await expect(puzzle).toHaveAttribute("data-joined", "false");
  await expect(page.locator(".puzzle-arrival")).toHaveCSS("opacity", "0");
  await puzzle.focus();
  await puzzle.press("Enter");
  await expect(puzzle).toHaveAttribute("data-joined", "true");
  await icon.focus();
  await icon.press("Enter");
  await expect.poll(() => arm.evaluate(el => el.getAnimations().filter(a => a.playState === "running").length)).toBe(1);
  const hit = page.locator(".home-action-hit");
  const primary = page.locator(".home-cta");
  const box = (await hit.boundingBox())!;
  await page.mouse.move(box.x + box.width - 3, box.y + box.height / 2);
  await expect.poll(() => hit.evaluate(el => el.style.getPropertyValue("--magnet-x"))).not.toBe("");
  expect(Math.abs(await hit.evaluate(el => parseFloat(el.style.getPropertyValue("--magnet-x"))))).toBeLessThanOrEqual(5);
  await page.mouse.move(0, 0);
  await expect.poll(() => hit.evaluate(el => el.style.getPropertyValue("--magnet-x"))).toBe("");
  await primary.focus();
  await expect(primary).toHaveCSS("translate", "0px");
  await page.emulateMedia({ reducedMotion: "reduce" });
  await expect(line).toHaveCSS("animation-name", "none");
  await icon.click();
  expect(await arm.evaluate(el => el.getAnimations().filter(a => a.playState === "running").length)).toBe(0);
  await expect(icon).toHaveCSS("transition-property", "none");
  await primary.press("Enter");
  await expect(page).toHaveURL(/\/workspace$/);
  const touch = await browser.newContext({ hasTouch: true, isMobile: true, viewport: { width: 320, height: 740 }, baseURL: "http://127.0.0.1:8877" });
  try {
    const mobile = await touch.newPage();
    await mobile.goto("/");
    await expect(mobile.locator(".home-cta")).toBeVisible();
    await expect(mobile.locator("#home-title > span").first()).toHaveCSS("animation-name", "none");
    await mobile.getByRole("button", { name: "拼接积木" }).tap();
    await expect(mobile.locator(".home-icon-reuse")).toHaveAttribute("data-joined", "true");
    expect(await mobile.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
    await mobile.locator(".home-action-hit").dispatchEvent("pointermove", { pointerType: "touch", clientX: 200, clientY: 400 });
    await expect(mobile.locator(".home-cta")).toHaveCSS("translate", "0px");
    await mobile.locator(".home-cta").tap();
    await expect(mobile).toHaveURL(/\/workspace$/);
  } finally { await touch.close(); }
});

test("empty and unavailable accounts never block entry or fake content", async ({ page }, testInfo) => {
  await page.route("**/api/creators?limit=4", route => route.fulfill({
    status: 200, json: { items: [], page: { total: 0, limit: 4, offset: 0 } },
  }));
  await page.goto("/");
  await expect(page.getByText("你的第一个创作账号，从这里开始。", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "创建账号", exact: false }).click();
  await expect(page).toHaveURL(/\/workspace$/);
  await page.unroute("**/api/creators?limit=4");
  await page.route("**/api/creators?limit=4", route => route.fulfill({
    status: 503, json: { error: { message: "受控故障：账号读取失败" } },
  }));
  await page.goto("/");
  await expect(page.getByText("暂时无法读取账号，你仍可以进入工作台。", { exact: true })).toBeVisible();
  await expect(page.locator(".home-account")).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath("home-read-error.png"), fullPage: true });
  await page.unroute("**/api/creators?limit=4");
  await page.getByRole("button", { name: "重新读取", exact: true }).click();
  await expect(page.locator(".home-account").first()).toBeVisible();
});
